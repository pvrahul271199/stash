// Converts the "Stash" wordmark to an SVG path (no font dependency) and writes
// public/logo.svg + components/ui/logoPath.ts. Run: npm run logo
import opentype from 'opentype.js';
import { readFileSync, writeFileSync } from 'node:fs';

const FONT = 'stash-mobile/node_modules/@expo-google-fonts/bricolage-grotesque/600SemiBold/BricolageGrotesque_600SemiBold.ttf';
const font = (() => { const b = readFileSync(FONT); return opentype.parse(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength)); })();
const size = 27;
// Manual layout (avoids opentype's GSUB shaping, which chokes on this font).
const glyphs = [...'Stash'].map((c) => font.charToGlyph(c));
const scale = size / font.unitsPerEm;
const adv = glyphs.map((g, i) => g.advanceWidth + (i ? font.getKerningValue(glyphs[i - 1], g) : 0));
const width = adv.reduce((a, b) => a + b, 0) * scale;
let x = 50 - width / 2;
const d = glyphs
  .map((g, i) => {
    x += (i ? font.getKerningValue(glyphs[i - 1], g) * scale : 0);
    const path = g.getPath(x, 57, size).toPathData(2);
    x += g.advanceWidth * scale;
    return path;
  })
  .join('');

const svg = (extra = '') => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100"${extra}>
  <rect width="100" height="100" rx="22" fill="#1E1B4B"/>
  <path d="${d}" fill="#fff"/>
  <rect x="38" y="67" width="24" height="5" rx="2.5" fill="#5EEAD4"/>
</svg>
`;
writeFileSync('public/logo.svg', svg(' width="512" height="512" role="img" aria-label="Stash"'));
writeFileSync('components/ui/logoPath.ts', `// Generated by scripts/gen-logo.mjs. Do not edit.\nexport const WORDMARK_PATH =\n  '${d}';\n`);
console.log('wrote logo.svg + logoPath.ts', d.length);
